def _rule_class(finding: Finding) -> str | None:
    """Класс находки, для которого есть подсказка (None — нет)."""
    rule = finding.rule_id or finding.tool
    if rule in _HINTS:
        return rule
    short = rule.rsplit("/", 1)[-1]
    return short if short in _HINTS else None


def hint_for(finding: Finding) -> str | None:
    """Подсказка к находке; None — класс неизвестен."""
    rule_class = _rule_class(finding)
    return _HINTS[rule_class] if rule_class else None


def hints_for(findings: Iterable[Finding]) -> list[tuple[str, str]]:
    """(класс, подсказка) по разу на класс, в порядке первой встречи."""
    seen: dict[str, str] = {}
    for finding in findings:
        rule_class = _rule_class(finding)
        if rule_class and rule_class not in seen:
            seen[rule_class] = _HINTS[rule_class]
    return list(seen.items())


# Общее правило над подсказками: агент, которому мешает линтер, охотнее
# всего глушит правило — это не исправление.
NO_SUPPRESS = "Чини причину в коде: подавление правила (eslint-disable, //nolint, # noqa, @ts-ignore) не считается исправлением."


def render_hints(findings: Iterable[Finding], bullet: str = "- ") -> list[str]:
    """Общее правило и строки «класс: подсказка» для вывода под списком находок."""
    hints = [f"{bullet}{rule_class}: {hint}" for rule_class, hint in hints_for(findings)]
    return [NO_SUPPRESS, *hints] if hints else []
